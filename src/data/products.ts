function product(
  id: string,
  name: string,
  category: ProductCategory,
  options: Partial<Pick<Product, 'size' | 'packSize' | 'variations' | 'price' | 'variationPrices' | 'image' | 'imageAlt'>> = {},
): Product {
  const photoIndex = categoryPhotoIndexes[category] ?? 0
  const photoId = categoryPhotoIds[category][photoIndex]
  if (photoId === undefined) {
    throw new Error(`Missing a unique product photo for the ${category} category.`)
  }
  categoryPhotoIndexes[category] = photoIndex + 1

  return {
    id,
    name,
    category,
    price: soldPrices[id] ?? null,
    image: pexelsImage(photoId, 600),
    imageAlt: `Representative Pexels fireworks photo for the ${category} category; not the exact branded product.`,
    ...options,
    ...(soldVariantPrices[id] ? { variationPrices: soldVariantPrices[id] } : {}),
  }
}

